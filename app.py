LOGO_FILE = "logo.png.jpg" if os.path.exists("logo.png.jpg") else "logo.png"
DEV_PHOTO = "developer.jpg.jpg" if os.path.exists("developer.jpg.jpg") else "developer.jpg"
USERS_FILE = "users_data.csv"
TRANSACTIONS_FILE = "transactions_data.csv"

def load_users():
    if os.path.exists(USERS_FILE):
        return pd.read_csv(USERS_FILE, dtype=str)
    return pd.DataFrame(columns=["Name", "Mobile", "Password"])

def save_users(df):
    df.to_csv(USERS_FILE, index=False, encoding="utf-8-sig")

def load_transactions():
    if os.path.exists(TRANSACTIONS_FILE):
        return pd.read_csv(TRANSACTIONS_FILE, dtype={"Mobile": str})
    return pd.DataFrame(columns=["ID", "Mobile", "User", "Date", "Type", "Category", "Amount", "Note"])

def save_transactions(df):
    df.to_csv(TRANSACTIONS_FILE, index=False, encoding="utf-8-sig")

def create_pdf(user_name, user_mobile, data_df, total_inc, total_exp, net_bal):
    pdf = FPDF()
    pdf.add_page()
    if os.path.exists(LOGO_FILE):
        try:
            pdf.image(LOGO_FILE, x=10, y=8, w=25)
        except Exception:
            pass
    pdf.set_font("Arial", "B", 16)
    pdf.cell(0, 10, "ARPK SmartSpend Pro - Financial Statement", ln=True, align="C")
    pdf.set_font("Arial", "", 10)
    pdf.cell(0, 6, f"User: {user_name} | Mobile: {user_mobile} | Date: {date.today()}", ln=True, align="C")
    pdf.ln(10)
    pdf.set_font("Arial", "B", 11)
    pdf.cell(0, 8, f"Total Income: Rs. {total_inc:,.2f}  |  Total Expense: Rs. {total_exp:,.2f}  |  Net Balance: Rs. {net_bal:,.2f}", ln=True)
    pdf.ln(4)

    pdf.set_fill_color(30, 60, 114)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Arial", "B", 10)
    pdf.cell(28, 8, "Date", 1, 0, "C", True)
    pdf.cell(25, 8, "Type", 1, 0, "C", True)
    pdf.cell(42, 8, "Category", 1, 0, "C", True)
    pdf.cell(30, 8, "Amount (Rs)", 1, 0, "C", True)
    pdf.cell(65, 8, "Note", 1, 1, "C", True)

    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Arial", "", 9)
    for _, row in data_df.iterrows():
        t_clean = "Income" if "Income" in str(row["Type"]) else "Expense"
        cat_clean = str(row["Category"]).encode("latin-1", "ignore").decode("latin-1")
        note_clean = str(row["Note"]).encode("latin-1", "ignore").decode("latin-1")[:30]
        pdf.cell(28, 7, str(row["Date"]), 1, 0, "C")
        pdf.cell(25, 7, t_clean, 1, 0, "C")
        pdf.cell(42, 7, cat_clean, 1, 0, "L")
        pdf.cell(30, 7, f"{float(row['Amount']):,.2f}", 1, 0, "R")
        pdf.cell(65, 7, note_clean, 1, 1, "L")

    pdf.ln(8)
    pdf.set_font("Arial", "I", 9)
    pdf.cell(0, 8, "Generated by ARPK SmartSpend Pro | Developed by Abhijeet Kakade", ln=True, align="C")
    return pdf.output(dest="S").encode("latin-1")

